def create_clustered_obstacles():
    obstacles = []
    # Cluster 1
    for x in range(2, 4):
        for y in range(2, 4):
            obstacles.append((x, y, 2))
    # Cluster 2
    for x in range(6, 8):
        for y in range(6, 8):
            obstacles.append((x, y, 2))
            
    return FailureCase(
        case_id="G",
        name="Clustered obstacles",
        hypothesis="Waypoints placed near dense clusters pull the search into local minima, negating the benefit of heuristic guidance.",
        challenge="Avoid local minima around clusters.",
        grid_size=(10, 10, 5),
        start=(0, 0, 2),
        goal=(9, 9, 2),
        obstacles=obstacles,
        manual_waypoints=[(3, 4, 2), (7, 5, 2)] # Placed right next to clusters
    )

def create_3d_vertical_detour():
    obstacles = []
    # A massive wall in the XY plane, stretching from z=0 to z=3
    for x in range(0, 10):
        for y in range(4, 6):
            for z in range(0, 4):
                obstacles.append((x, y, z))
                
    return FailureCase(
        case_id="H",
        name="3D vertical detour",
        hypothesis="A strictly horizontal waypoint sequence will fail to utilize the vertical dimension, whereas standard A* will easily go over the wall.",
        challenge="Navigate in 3D over a barrier.",
        grid_size=(10, 10, 6),
        start=(5, 1, 1),
        goal=(5, 8, 1),
        obstacles=obstacles,
        manual_waypoints=[(5, 3, 1), (5, 7, 1)] # Horizontal waypoints that crash into the wall
    )

