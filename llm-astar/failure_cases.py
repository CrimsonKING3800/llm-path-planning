from environment import Grid3D

class FailureCase:
    def __init__(self, case_id, name, hypothesis, challenge, grid_size, start, goal, obstacles, manual_waypoints=None):
        self.case_id = case_id
        self.name = name
        self.hypothesis = hypothesis
        self.challenge = challenge
        self.grid_size = grid_size
        self.start = start
        self.goal = goal
        self.obstacles = obstacles
        self.manual_waypoints = manual_waypoints or []
        self.waypoint_variants = {}

    def get_env(self):
        env = Grid3D(self.grid_size)
        env.obstacles = set(self.obstacles)
        return env

def create_u_shape_trap():
    obstacles = []
    # U-shape opening to the left (negative x)
    for y in range(2, 9):
        obstacles.append((8, y, 2)) # base
    for x in range(4, 9):
        obstacles.append((x, 2, 2)) # bottom leg
        obstacles.append((x, 8, 2)) # top leg
    
    return FailureCase(
        case_id="A",
        name="U-shaped obstacle trap",
        hypothesis="A waypoint inside a concave obstacle will trap the search, leading to massive node expansions as the heuristic forces it against the wall.",
        challenge="Navigate out of a U-shaped local minimum.",
        grid_size=(15, 15, 5),
        start=(2, 5, 2),
        goal=(12, 5, 2),
        obstacles=obstacles,
        manual_waypoints=[(7, 5, 2)] # Inside the U-shape
    )

