def create_narrow_corridor():
    obstacles = []
    # Create a wide path at y >= 6, and a narrow zig-zag path at y <= 3
    for x in range(0, 10):
        obstacles.append((x, 4, 2))
    obstacles.append((4, 2, 2))
    obstacles.append((5, 1, 2))
    
    return FailureCase(
        case_id="C",
        name="Narrow corridor",
        hypothesis="Directing the search into a narrow, cluttered corridor increases search time compared to exploring a wide-open alternative.",
        challenge="Navigate a tight space instead of open space.",
        grid_size=(10, 10, 5),
        start=(1, 5, 2),
        goal=(8, 5, 2),
        obstacles=obstacles,
        manual_waypoints=[(4, 1, 2)] # Forces it into the narrow corridor
    )

def create_dead_end():
    obstacles = []
    # Dead end passage
    for x in range(2, 8):
        obstacles.append((x, 2, 2))
